"""v0.3.5+: Re-render the Blueprint 8-variant WAVs through FluidR3_GM.

The original Blueprint WAVs were generated by `compose_blueprint.render_blueprint_wav`
(additive-sine per-program-family).  This script uses `render_soundfont.render_blueprint_soundfont`
to produce real-instrument Blueprint WAVs (piano, koto, strings, etc.) so the
.wav file matches what the Live button plays.

Blueprint mode has 12 000+ notes and the long-duration roof voice can pile
up to 150+ simultaneous notes; the renderer thins per-voice polyphony
(default max 40 per voice) to stay within tinysoundfont's voice pool.
"""
from __future__ import annotations
import json
import sys
import time
from pathlib import Path

sys.path.insert(0, r'D:\Hackathon_SKD_Laptop\MusicPhoto\experiment\vendor')
sys.path.insert(0, r'D:\Hackathon_SKD_Laptop\MusicPhoto\experiment')

import run as lab
import compose_blueprint as cbp
import render_soundfont as rsf

OUT = lab.OUT


def main() -> int:
    sf = rsf.find_soundfont()
    if not sf:
        print('[bp-sf] no FluidR3 .sf2/.sf3 found, aborting')
        return 1
    print(f'[bp-sf] using soundfont: {sf}')
    # Use a SHARED pool so the 7s sfload only happens once for all
    # 48 Blueprint renders (5 voices each, ~7s × 5 × 48 = 28 minutes
    # vs ~12s with the pool).
    pool = rsf._SoundFontPool.get(sf, rate=44100, gain=1.2)
    n_rendered = 0
    for idx in range(6):
        bp_path = OUT / f'sample{idx}-blueprint.json'
        if not bp_path.exists():
            print(f'[bp-sf] {bp_path} missing, skipping')
            continue
        bp = json.loads(bp_path.read_text(encoding='utf-8'))
        for variant in cbp.VARIANTS:
            wav_path = OUT / f'sample{idx}-bp-{variant}.wav'
            notes = cbp.compose_blueprint(bp, variant)
            t0 = time.time()
            rsf.render_blueprint_soundfont(
                notes, wav_path, sf_path=sf,
                total_seconds=13.5, rate=44100, max_per_voice=40,
                pool=pool,
            )
            dt = time.time() - t0
            print(f'[bp-sf] sample{idx} {variant}: {len(notes)} notes '
                  f'-> {wav_path.name} in {dt:.2f}s')
            n_rendered += 1
    pool.close()
    print(f'[bp-sf] done: {n_rendered} blueprint wav files re-rendered with FluidR3_GM')
    return 0


if __name__ == '__main__':
    sys.exit(main())
